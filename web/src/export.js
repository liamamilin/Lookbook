const typeLine = (k, v) =>
  `- ${k}: ${[v.fontFamily, v.fontSize != null && withPx(v.fontSize), v.fontWeight != null && `weight ${v.fontWeight}`, v.lineHeight != null && `line-height ${v.lineHeight}`, v.letterSpacing != null && `letter-spacing ${withPx(v.letterSpacing)}`]
    .filter(Boolean)
    .join(' · ')}`

const COMP_KEYS = ['backgroundColor', 'textColor', 'rounded', 'padding', 'height', 'border', 'borderColor']

/**
 * @param {object} t           template
 * @param {object} opts
 * @param {'zh'|'en'} opts.lang
 * @param {string} [opts.description]  localised description
 * @param {string} [opts.raw]          full DESIGN.md text to append
 */
export function toPrompt(t, { lang = 'zh', description = '', raw = '' } = {}) {
  const P = PROMPT[lang] || PROMPT.zh
  const r = t.roles
  const s = tokenSet(t)
  const lines = [P.intro(t.name), '']
  if (!t.structured) lines.push(P.approx, '')

  lines.push(`## ${P.core}`)
  for (const k of ['canvas', 'ink', 'body', 'muted', 'primary', 'onPrimary', 'surface', 'hairline']) lines.push(`- ${P[k]}: ${r[k]}`)

  // Type: a representative subset (largest display, a heading, body, button, caption).
  const typo = s.typography.slice().sort((a, b) => px(b[1].fontSize) - px(a[1].fontSize))
  const pickType = [typo[0], ...typo.filter(([k]) => /heading|title|body|button|caption|label/.test(k)).slice(0, 6)]
  const seen = new Set()
  const typeLines = pickType.filter((x) => x && !seen.has(x[0]) && seen.add(x[0])).map(([k, v]) => typeLine(k, v))
  if (typeLines.length) lines.push('', `## ${P.type}`, ...typeLines)
  else if (s.fonts.length) lines.push('', `## ${P.type}`, ...s.fonts.map(([k, v]) => `- ${k}: ${v}`))

  if (s.radius.length) lines.push('', `## ${P.radius}`, s.radius.map(([k, v]) => `${k} ${v}`).join(' · '))
  if (s.spacing.length) lines.push('', `## ${P.spacing}`, s.spacing.map(([k, v]) => `${k} ${v}`).join(' · '))

  const comps = entries(t.tokens.components)
    .filter(([k, v]) => v && typeof v === 'object' && /^(button|btn|cta|card|input|text-input|nav|pill|badge|tag|link)/.test(k) && !/(pressed|hover|active|focus|disabled)/.test(k))
    .slice(0, 10)
  if (comps.length) {
    lines.push('', `## ${P.comps}`)
    for (const [k, v] of comps) {
      const props = COMP_KEYS.filter((p) => v[p] != null).map((p) => `${p} ${v[p]}`)
      if (typeof v.typography === 'object' && v.typography.fontSize) props.push(`font ${withPx(v.typography.fontSize)}/${v.typography.fontWeight ?? ''}`)
      lines.push(`- ${k}: ${props.join(', ')}`)
    }
  }

  if (s.colors.length) lines.push('', `## ${P.palette}`, s.colors.map(([k, v]) => `${k} ${v}`).join(' · '))
  if (description) lines.push('', `## ${P.character}`, description)
  lines.push('', `## ${P.rules}`, ...P.ruleList.map((x) => `- ${x}`))
  // Four backticks so code fences inside the DESIGN.md don't close the block.
  if (raw) lines.push('', `## ${P.full}`, '', '````markdown', raw.trim(), '````')
  lines.push('', P.task, '')
  return lines.join('\n')
}
