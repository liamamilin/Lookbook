// Turns a parsed template's resolved tokens into files people can use directly:
// CSS variables, Tailwind v4 @theme, Tailwind v3 config, W3C DTCG JSON, and an AI prompt.
import { isColor, luminance } from './color.js'
import { px } from './render.js'

const entries = (o) => Object.entries(o || {})

// CSS-safe token name.
const slugKey = (k) =>
  String(k)
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'token'

const withPx = (v) => (typeof v === 'number' && v !== 0 ? `${v}px` : String(v))

// Only real colour values become colour tokens (no gradients, refs or 'transparent').
const exportableColor = (v) => isColor(v) && v.trim() !== 'transparent' && luminance(v) != null

/* ---------------- normalised token set ---------------- */

// Collapse a template (structured or legacy) into one flat shape the writers share.
export function tokenSet(t) {
  const colors = []
  if (!t.structured && t.legacyColors?.length) {
    const seen = new Set()
    for (const c of t.legacyColors) {
      const name = slugKey(c.name)
      if (seen.has(name) || !exportableColor(c.value)) continue
      seen.add(name)
      colors.push([name, c.value])
    }
  } else {
    for (const [k, v] of entries(t.tokens.colors)) if (exportableColor(v)) colors.push([slugKey(k), v])
  }

  const typography = entries(t.tokens.typography)
    .filter(([, v]) => v && typeof v === 'object')
    .map(([k, v]) => [slugKey(k), v])

  // Distinct font stacks, named after the first type role that uses them (display-xl -> display).
  const fonts = []
  const fontOf = new Map()
  const addFont = (stack, role) => {
    if (!stack || fontOf.has(stack)) return
    let name = slugKey(role).replace(/-(xxxl|xxl|xl|lg|md|sm|xs|xxs|\d+|large|medium|small|regular|bold|light|strong)$/g, '')
    while (fonts.some(([n]) => n === name)) name += '-alt'
    fonts.push([name, stack])
    fontOf.set(stack, name)
  }
  if (!t.structured && t.legacyFonts?.length) t.legacyFonts.forEach((f) => addFont(f.stack, f.role))
  typography.forEach(([k, v]) => addFont(v.fontFamily, k))

  const radius = entries(t.tokens.rounded).map(([k, v]) => [slugKey(k), withPx(v)])
  const spacing = entries(t.tokens.spacing)
    .filter(([, v]) => typeof v === 'number' || typeof v === 'string')
    .map(([k, v]) => [slugKey(k), withPx(v)])

  return { colors, typography, fonts, fontOf, radius, spacing }
}

/* ---------------- CSS variables ---------------- */

export function toCSS(t) {
  const s = tokenSet(t)
  const out = [`/* ${t.name} — generated by Lookbook from design-md/${t.slug}/DESIGN.md */`, ':root {']
  const section = (title, lines) => {
    if (!lines.length) return
    out.push(`  /* ${title} */`, ...lines.map((l) => `  ${l}`), '')
  }
  section('Colors', s.colors.map(([k, v]) => `--color-${k}: ${v};`))
  section('Font families', s.fonts.map(([k, v]) => `--font-${k}: ${v};`))
  section(
    'Typography',
    s.typography.flatMap(([k, v]) =>
      [
        v.fontFamily && `--text-${k}-family: var(--font-${s.fontOf.get(v.fontFamily)});`,
        v.fontSize != null && `--text-${k}-size: ${withPx(v.fontSize)};`,
        v.fontWeight != null && `--text-${k}-weight: ${v.fontWeight};`,
        v.lineHeight != null && `--text-${k}-line-height: ${v.lineHeight};`,
        v.letterSpacing != null && `--text-${k}-letter-spacing: ${withPx(v.letterSpacing)};`,
      ].filter(Boolean),
    ),
  )
  section('Radius', s.radius.map(([k, v]) => `--radius-${k}: ${v};`))
  section('Spacing', s.spacing.map(([k, v]) => `--space-${k}: ${v};`))
  if (out[out.length - 1] === '') out.pop()
  out.push('}', '')
  return out.join('\n')
}

/* ---------------- Tailwind v4 (@theme) ---------------- */

export function toTailwind4(t) {
  const s = tokenSet(t)
  const out = [`/* ${t.name} — generated by Lookbook. Paste after @import "tailwindcss"; */`, '@theme {']
  const section = (title, lines) => {
    if (!lines.length) return
    out.push(`  /* ${title} */`, ...lines.map((l) => `  ${l}`), '')
  }
  section('Colors → bg-*, text-*, border-*', s.colors.map(([k, v]) => `--color-${k}: ${v};`))
  section('Fonts → font-*', s.fonts.map(([k, v]) => `--font-${k}: ${v};`))
  section(
    'Type scale → text-*',
    s.typography.flatMap(([k, v]) =>
      [
        v.fontSize != null && `--text-${k}: ${withPx(v.fontSize)};`,
        v.fontSize != null && v.lineHeight != null && `--text-${k}--line-height: ${v.lineHeight};`,
        v.fontSize != null && v.letterSpacing != null && `--text-${k}--letter-spacing: ${withPx(v.letterSpacing)};`,
        v.fontSize != null && v.fontWeight != null && `--text-${k}--font-weight: ${v.fontWeight};`,
      ].filter(Boolean),
    ),
  )
  section('Radius → rounded-*', s.radius.map(([k, v]) => `--radius-${k}: ${v};`))
  section('Spacing → p-*, m-*, gap-*', s.spacing.map(([k, v]) => `--spacing-${k}: ${v};`))
  if (out[out.length - 1] === '') out.pop()
  out.push('}', '')
  return out.join('\n')
}

/* ---------------- Tailwind v3 config ---------------- */

const splitStack = (stack) =>
  String(stack)
    .split(',')
    .map((f) => f.trim().replace(/^['"]|['"]$/g, ''))
    .filter(Boolean)

export function toTailwind3(t) {
  const s = tokenSet(t)
  const obj = (pairs) => Object.fromEntries(pairs)
  const theme = {
    colors: obj(s.colors),
    fontFamily: obj(s.fonts.map(([k, v]) => [k, splitStack(v)])),
    fontSize: obj(
      s.typography
        .filter(([, v]) => v.fontSize != null)
        .map(([k, v]) => {
          const opts = {}
          if (v.lineHeight != null) opts.lineHeight = String(v.lineHeight)
          if (v.letterSpacing != null) opts.letterSpacing = withPx(v.letterSpacing)
          if (v.fontWeight != null) opts.fontWeight = String(v.fontWeight)
          return [k, [withPx(v.fontSize), opts]]
        }),
    ),
    borderRadius: obj(s.radius),
    spacing: obj(s.spacing),
  }
  for (const k of Object.keys(theme)) if (!Object.keys(theme[k]).length) delete theme[k]
  return `// ${t.name} — generated by Lookbook from design-md/${t.slug}/DESIGN.md
/** @type {import('tailwindcss').Config} */
module.exports = {
  theme: {
    extend: ${JSON.stringify(theme, null, 2).replace(/\n/g, '\n    ')},
  },
}
`
}

/* ---------------- W3C DTCG JSON ---------------- */

export function toDTCG(t) {
  const s = tokenSet(t)
  const group = (type, pairs, map = (v) => v) =>
    Object.fromEntries(pairs.map(([k, v]) => [k, { $type: type, $value: map(v) }]))
  const json = {
    $description: `${t.name} — generated by Lookbook from design-md/${t.slug}/DESIGN.md`,
    color: group('color', s.colors),
    fontFamily: group('fontFamily', s.fonts, splitStack),
    typography: Object.fromEntries(
      s.typography.map(([k, v]) => {
        const value = {}
        if (v.fontFamily) value.fontFamily = `{fontFamily.${s.fontOf.get(v.fontFamily)}}`
        if (v.fontSize != null) value.fontSize = withPx(v.fontSize)
        if (v.fontWeight != null) value.fontWeight = v.fontWeight
        if (v.lineHeight != null) value.lineHeight = v.lineHeight
        if (v.letterSpacing != null) value.letterSpacing = withPx(v.letterSpacing)
        return [k, { $type: 'typography', $value: value }]
      }),
    ),
    borderRadius: group('dimension', s.radius),
    spacing: group('dimension', s.spacing),
  }
  for (const k of Object.keys(json)) if (typeof json[k] === 'object' && !Object.keys(json[k]).length) delete json[k]
  return JSON.stringify(json, null, 2) + '\n'
}

